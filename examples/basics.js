// Variables
const name = "Vishara";
let age = 22;

console.log(name);
console.log(age);

// Changing a let variable
age = 23;

console.log(age);

// Data types
const isStudent = true;
const score = 85.5;

console.log(typeof name);
console.log(typeof age);
console.log(typeof isStudent);
console.log(typeof score);

// Arithmetic
let a = 10;
let b = 3;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);

// Comparison
console.log(age > 18);
console.log(age === 23);

// Template literal
console.log(`My name is ${name} and I am ${age} years old.`);
